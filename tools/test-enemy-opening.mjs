import assert from 'node:assert/strict';
import {startCharacterAtHome} from '../extension/genshin-dialogue-ui/character-location.js';
import {activeEnemies} from '../extension/genshin-dialogue-ui/combat-state.js';
globalThis.location=new URL('http://localhost/');
const point=(id,pool)=>({id,label:id,path:'/background.webp',waypoint:{mapId:'teyvat',x:1,y:1},wilderness:true,enemyPool:pool,residents:[]});
const enemy={name:'Hilichurl Fighter',avatar:'enemy.png',data:{extensions:{silly_teyvat:{role:'enemy'}}}};
const ctx={characters:[enemy],characterId:0,groupId:null,groups:[],chat:[{mes:'Hello'}],chatMetadata:{},extensionSettings:{genshin_dialogue_ui:{backgroundRegions:[{id:'mond',name:'Mondstadt',locations:[point('other',[]),point('one',['enemy.png']),point('two',['enemy.png'])]}]}},saveSettingsDebounced(){},saveMetadataDebounced(){},setExtensionPrompt(){}};
assert.equal(startCharacterAtHome(ctx,()=>.99),true);
assert.equal(ctx.chatMetadata.silly_teyvat_world.location.id,'two');
assert.deepEqual(ctx.chatMetadata.silly_teyvat_cast.encounter.enemies,['enemy.png']);
assert.deepEqual(activeEnemies(ctx).map(e=>e.avatar),['enemy.png']);
assert.equal(startCharacterAtHome(ctx,()=>0),false);
assert.equal(ctx.chatMetadata.silly_teyvat_world.location.id,'two');
console.log('PASS enemy opening selects a matching habitat, starts the encounter, and preserves saved locations');
