import assert from 'node:assert/strict';
import fs from 'node:fs';
import {NPC_KITS,npcKit} from '../extension/genshin-dialogue-ui/npc-kits.js';
import {defaultKit,defaultKitHp,foeKit} from '../extension/genshin-dialogue-ui/combat-kits.js';
import {enemyTier,WEAK_TIER,BOSS_TIER,rollLoot,ITEMS} from '../extension/genshin-dialogue-ui/battle-items.js';
import {defeatGuildStaff,leaveDefeatedGuildStaff} from '../extension/genshin-dialogue-ui/guild.js';
import {locationResidents,rollLocationEncounter} from '../extension/genshin-dialogue-ui/location-encounters.js';
import {castMembership} from '../extension/genshin-dialogue-ui/location-cast.js';
import {characterProperties} from '../extension/genshin-dialogue-ui/character-properties.js';
import {worldScalePrompt} from '../extension/genshin-dialogue-ui/world-data.js';
globalThis.location=new URL('http://localhost/');
const properties=JSON.parse(fs.readFileSync(new URL('../extension/genshin-dialogue-ui/assets/character-properties.json',import.meta.url)));
const names=Object.entries(properties).filter(([,p])=>p.role!=='enemy'&&p.playable===false).map(([n])=>n);
assert.equal(names.length,NPC_KITS.size);
for(const name of names){
 const kit=defaultKit(name),npc=npcKit(name);
 assert.ok(npc,`${name}: NPC kit missing`);assert.equal(defaultKitHp(name,false),npc.hp);assert.equal(kit.moves.length,3);
 assert.equal(new Set(kit.moves.map(m=>m.name)).size,3,`${name}: move names`);
 assert.ok(kit.moves.every(m=>m.effects.length>0),`${name}: effects`);
 assert.deepEqual(foeKit(kit).moves.map(m=>m.kind),['basic','basic','special']);
 if(npc.hp<=30)assert.equal(enemyTier({name,maxHp:npc.hp}),WEAK_TIER);
}
assert.ok(npcKit('Katheryne').hp>90);assert.equal(enemyTier({name:'Katheryne',maxHp:110}),BOSS_TIER);
assert.ok(rollLoot([{name:'Adel',maxHp:22}],{random:()=>0,pool:Object.keys(ITEMS)}).every(id=>ITEMS[id].rarity===1));
const k={name:'Katheryne',avatar:'Katheryne.png',data:{}},n={name:'Narrator',avatar:'silly-teyvat-narrator.png'},guild={id:'g',label:"Adventurers' Guild, Mondstadt",residents:[],path:'/guild.webp',waypoint:{mapId:'teyvat',x:0,y:0}},road={id:'r',label:'Road',residents:[],wilderness:true};
const ctx={characters:[k,n],characterId:0,groupId:null,groups:[],chat:[],chatMetadata:{silly_teyvat_world:{location:{id:'g'}},silly_teyvat_cast:{core:['Katheryne.png'],managed:[],placements:{},opening:{avatar:'Katheryne.png',active:true},encounter:{key:'visit',locationId:'g',present:['Katheryne.png'],travellers:[],enemies:[]}},silly_teyvat_combat:{version:2,visits:{},party:{'Katheryne.png':{hp:0,maxHp:110}},battles:{'duel:Katheryne.png':{round:3}},events:[]}},extensionSettings:{genshin_dialogue_ui:{backgroundRegions:[{id:'mond',name:'Mondstadt',locations:[guild,road]}]}},saveSettingsDebounced(){},saveMetadataDebounced(){}};
assert.equal(characterProperties(ctx,k).maxHp,110);
assert.equal(defeatGuildStaff(ctx,k.avatar),true);
assert.equal(locationResidents(ctx,'g').some(c=>c.avatar===k.avatar),false);
assert.equal(castMembership(ctx).members.includes(k.avatar),false);
assert.equal(leaveDefeatedGuildStaff(ctx,{id:'g'},{id:'g'}),false);
assert.equal(leaveDefeatedGuildStaff(ctx,{id:'g'},{id:'r'}),true);
assert.equal(ctx.chatMetadata.silly_teyvat_combat.party[k.avatar].hp,110);
assert.equal(ctx.chatMetadata.silly_teyvat_combat.battles['duel:Katheryne.png'],undefined);
ctx.chatMetadata.silly_teyvat_world.location={id:'r'};
assert.ok(rollLocationEncounter(ctx,'g',[],{random:()=>.5}).present.includes(k.avatar));
assert.equal(ctx.chatMetadata.silly_teyvat_cast.guildStaffReturned,true);
ctx.chatMetadata.silly_teyvat_world={regionId:'mond',location:guild};
assert.match(worldScalePrompt(ctx),/Katheryne is at the counter again.*does not acknowledge or remember it/);
console.log(`PASS ${names.length} individual NPC kits, weak loot, and Katheryne defeat/departure/return`);
